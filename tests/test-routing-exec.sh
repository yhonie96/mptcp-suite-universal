#!/bin/sh
set -eu
F=mptcp-suite-routing/files/usr/libexec/mptcp-suite/routing-exec
test -x "$F"
grep -Fq 'MODE="${1:---dry-run}"' "$F"
grep -Fq "flock -n 9" "$F"
grep -Fq "MPTCP_PAUSED_FILE" "$F"
grep -Fq "MPTCP_ROUTING_APPLY" "$F"
grep -Fq "snapshot()" "$F"
grep -Fq "rollback()" "$F"
! grep -Fq "table main" "$F"
grep -Fq "allocated" "$F"
grep -Fq "ERROR=not_allocated" "$F"
grep -Fq "primary_table" "$F"
grep -Fq "secondary_table" "$F"
grep -Fq "tproxy_table" "$F"
grep -Fq "validate_config()" "$F"
grep -Fq "ERROR=incomplete_configuration" "$F"
grep -Fq "ERROR=duplicate_table_id" "$F"
grep -Fq "ERROR=table_id_range" "$F"
grep -Fq "primary_priority" "$F"
grep -Fq "secondary_priority" "$F"
grep -Fq "tproxy_priority" "$F"
grep -Fq 'ip route show table "$PT"' "$F"
grep -Fq 'ip route show table "$ST"' "$F"
grep -Fq 'ip route show table "$TT"' "$F"
grep -Fq "ERROR=incomplete_priority" "$F"
grep -Fq "ERROR=duplicate_priorities" "$F"
grep -Fq "ERROR=priority_range" "$F"
grep -Fq "TABLE_PRIMARY" "$F"
grep -Fq "TABLE_SECONDARY" "$F"
grep -Fq "TABLE_TPROXY" "$F"
grep -Fq "RULES" "$F"
grep -Fq "restore_snapshot()" "$F"
grep -Fq 'ip rule del priority "$BP"' "$F"
grep -Fq 'ip rule del priority "$PP"' "$F"
grep -Fq 'ip rule del priority "$TP"' "$F"
grep -Fq 'ip route flush table "$PT"' "$F"
grep -Fq 'ip route flush table "$ST"' "$F"
grep -Fq 'ip route flush table "$TT"' "$F"
! grep -Fq "=== MAIN ===" "$F"
! grep -Fq "lookup main" "$F"
grep -Fq "TABLE_PRIMARY" "$F"
grep -Fq "TABLE_SECONDARY" "$F"
grep -Fq "TABLE_TPROXY" "$F"
grep -Fq "MPTCP_ROUTING_RESTORE_BIN" "$F"
grep -Fq '"$RESTORE" "$SNAP" "$PT" "$ST" "$TT" "$BP" "$PP" "$TP"' "$F"
grep -Fq "ERROR=apply_not_implemented" "$F"
grep -Fq "run_plan()" "$F"
grep -Fq "ERROR=unsafe_command" "$F"
! grep -Eq "eval|sh -c" "$F"
grep -Fq "MPTCP_ROUTING_PLAN_FILE" "$F"
grep -Fq 'table "$PT"' "$F"
grep -Fq 'table "$ST"' "$F"
grep -Fq 'table "$TT"' "$F"
grep -Fq 'priority "$BP"' "$F"
grep -Fq 'priority "$PP"' "$F"
grep -Fq 'priority "$TP"' "$F"
grep -Fq -- "--test-plan" "$F"
grep -Fq "MPTCP_ROUTING_TEST" "$F"
grep -Fq "ERROR=test_locked" "$F"
grep -Fq "MPTCP_TEST_BM" "$F"
grep -Fq "MPTCP_TEST_PM" "$F"
grep -Fq "MPTCP_TEST_TM" "$F"
grep -Fq '$BP:$BM:$PT' "$F"
grep -Fq '$PP:$PM:$ST' "$F"
grep -Fq '$TP:$TM:$TT' "$F"
grep -Fq "MPTCP_TEST_BM" "$F"
grep -Fq "MPTCP_TEST_PM" "$F"
grep -Fq "MPTCP_TEST_TM" "$F"
grep -Fq '$BP:$BM:$PT' "$F"
grep -Fq '$PP:$PM:$ST' "$F"
grep -Fq '$TP:$TM:$TT' "$F"
echo ROUTING_EXEC_STRUCTURE_OK
