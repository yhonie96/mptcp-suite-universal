#!/bin/sh
set -eu
F=mptcp-suite-routing/files/usr/libexec/mptcp-suite/routing-exec
test -x "$F"
grep -Fq 'MODE="${1:---dry-run}"' "$F"
grep -Fq "flock -n 9" "$F"
grep -Fq "MPTCP_PAUSED_FILE" "$F"
grep -Fq "MPTCP_ROUTING_APPLY" "$F"
grep -Fq "snapshot()" "$F"
grep -Fq "rollback()" "$F"
! grep -Fq "table main" "$F"
grep -Fq "allocated" "$F"
grep -Fq "ERROR=not_allocated" "$F"
grep -Fq "primary_table" "$F"
grep -Fq "secondary_table" "$F"
grep -Fq "tproxy_table" "$F"
grep -Fq "validate_config()" "$F"
grep -Fq "ERROR=incomplete_configuration" "$F"
grep -Fq "ERROR=duplicate_table_id" "$F"
grep -Fq "ERROR=table_id_range" "$F"
grep -Fq "primary_priority" "$F"
grep -Fq "secondary_priority" "$F"
grep -Fq "tproxy_priority" "$F"
grep -Fq 'ip route show table "$PT"' "$F"
grep -Fq 'ip route show table "$ST"' "$F"
grep -Fq 'ip route show table "$TT"' "$F"
grep -Fq "ERROR=incomplete_priority" "$F"
grep -Fq "ERROR=duplicate_priorities" "$F"
grep -Fq "ERROR=priority_range" "$F"
echo ROUTING_EXEC_STRUCTURE_OK
